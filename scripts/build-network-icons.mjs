/**
 * Copy the network logos Cons uses from @web3icons/core (MIT) into
 * src/lib/network-icons.js, so the site ships them without a runtime
 * dependency or CDN. Rerun after adding a network: node scripts/build-network-icons.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

// The package does not export its file tree, so read it from node_modules directly.
const dir = fileURLToPath(new URL("../node_modules/@web3icons/core/dist/svgs/networks/", import.meta.url));

/* Cons network id -> web3icons file name. */
const ICONS = {
  solana: "solana",
  ethereum: "ethereum",
  base: "base",
  arbitrum: "arbitrum-one",
  bnb: "binance-smart-chain",
  hyperevm: "hyper-evm",
  avalanche: "avalanche",
  optimism: "optimism",
  polygon: "polygon",
  robinhood: "robinhood",
  arc: "arc",
};

const TOKENS = { USDC: "USDC", USDT: "USDT" };

function read(variant, file, kind = "networks") {
  const source = readFileSync(join(dir, "..", kind, variant, `${file}.svg.js`), "utf8");
  const svg = source.match(/'(<svg[\s\S]*?<\/svg>)\\n'/)?.[1];
  if (!svg) throw new Error(`No svg in ${variant}/${file}`);
  return svg
    .replace(/\\n\s*/g, "")
    .replace(/ width="24" height="24"/, "")
    .replace(/ class="web3icons"/, ' aria-hidden="true" focusable="false"');
}

const table = (variant) =>
  Object.entries(ICONS)
    .map(([id, file]) => `  ${id}: ${JSON.stringify(read(variant, file))},`)
    .join("\n");

const tokenTable = Object.entries(TOKENS)
  .map(([symbol, file]) => `  ${symbol}: ${JSON.stringify(read("background", file, "tokens"))},`)
  .join("\n");

writeFileSync(
  new URL("../src/lib/network-icons.js", import.meta.url),
  `/* Generated by scripts/build-network-icons.mjs from @web3icons/core (MIT). Do not edit. */

/* Logo on its brand colour (square), shown as round badges. */
export const networkIcons = Object.freeze({
${table("background")}
});

/* The bare mark, for placing inside an existing node shape (landing figures). */
export const networkMarks = Object.freeze({
${table("branded")}
});

/* Token logos on their brand colour, by symbol. */
export const tokenIcons = Object.freeze({
${tokenTable}
});
`,
);
console.log(`network icons: ${Object.keys(ICONS).length} networks x 2 variants`);
