/**
 * Copy the network logos (background variant: logo on its brand colour) Cons uses from @web3icons/core (MIT) into
 * src/lib/network-icons.js, so the site ships them without a runtime
 * dependency or CDN. Rerun after adding a network: node scripts/build-network-icons.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

// The package does not export its file tree, so read it from node_modules directly.
const dir = fileURLToPath(new URL("../node_modules/@web3icons/core/dist/svgs/networks/background/", import.meta.url));

/* Cons network id -> web3icons file name. */
const ICONS = {
  solana: "solana",
  ethereum: "ethereum",
  base: "base",
  arbitrum: "arbitrum-one",
  bnb: "binance-smart-chain",
  hyperevm: "hyper-evm",
  avalanche: "avalanche",
  optimism: "optimism",
  polygon: "polygon",
  robinhood: "robinhood",
  arc: "arc",
};

const entries = Object.entries(ICONS).map(([id, file]) => {
  const source = readFileSync(join(dir, `${file}.svg.js`), "utf8");
  const svg = source.match(/'(<svg[\s\S]*?<\/svg>)\\n'/)?.[1];
  if (!svg) throw new Error(`No svg in ${file}`);
  const clean = svg
    .replace(/\\n\s*/g, "")
    .replace(/ width="24" height="24"/, "")
    .replace(/ class="web3icons"/, ' aria-hidden="true" focusable="false"');
  return `  ${id}: ${JSON.stringify(clean)},`;
});

writeFileSync(
  new URL("../src/lib/network-icons.js", import.meta.url),
  `/* Generated by scripts/build-network-icons.mjs from @web3icons/core (MIT). Do not edit. */
export const networkIcons = Object.freeze({
${entries.join("\n")}
});
`,
);
console.log(`network icons: ${entries.length}`);
